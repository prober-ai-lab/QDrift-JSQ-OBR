# compression time -- OBR vs selected QDrift wall-clock, from logged compress_s
# --------------------------------------------------------------------------- #
COMPRESS_SPEC = [
    (model, bits, pattern)
    for model in ("llama2-7b", "llama3.1-8b", "llama2-13b")
    for bits, pattern in (("W4A4", "s70"), ("W4A4", "4to8p-obs"), ("W2A16", "s50"))
]


def compression_time(runs) -> tuple[str, str]:
    """OBR vs QDrift compression wall-clock (one run each; QDrift adds the
    reference OBR solve that its derived mixture needs)."""
    blocks: list[list[str]] = []
    for model, bits, pattern in COMPRESS_SPEC:
        tags = runs.get((model, bits, pattern, CALIB))
        if not tags:
            continue
        obr, _, _ = T.select(tags)
        qd = T.qdrift_of(tags)
        if obr is None or qd is None:
            continue
        o, q = obr.get("compress_s"), qd.get("compress_s")
        if not o or not q:
            print(f"  skip compress row {model} {bits} {pattern}: no compress_s")
            continue
        if not blocks or blocks[-1][0].split(" & ")[0] != MODEL_DISP[model]:
            blocks.append([])
        blocks[-1].append(" & ".join([
            MODEL_DISP[model], _setting_label(bits, pattern),
            f"{o / 60:.0f}", f"{q / 60:.0f}", f"${q / o:.2f}\\times$",
        ]))
    if not blocks:
        raise SystemExit("compression_time: no paired compress_s found")
    header = r"Model & Setting & OBR (min) & QDrift (min) & ratio"
    return "compression_time", _render("ll" + "c" * 3, header, blocks)


