# Table 5 -- mask selection (7B pairwise 4:8)
# --------------------------------------------------------------------------- #
def mask_selection(runs) -> tuple[str, str]:
    score = runs.get(("llama2-7b", "W4A4", "4to8p", CALIB), {})
    obs = runs.get(("llama2-7b", "W4A4", "4to8p-obs", CALIB), {})
    if not score or not obs:
        raise SystemExit("mask_selection: need both 4to8p (score) and 4to8p-obs grids")
    obr_obs, _, _ = T.select(obs)
    qd = T.qdrift_of(obs)
    if qd is None:
        raise SystemExit("mask_selection: no QDrift run on the exact mask")
    rows = [
        "OBR & SparseGPT pair score & " + T.ppl_cell(score.get("seq")),
        "OBR & Exact block-sequential & " + T.ppl_cell(obr_obs),
        "QDrift & Exact block-sequential & " + f"\\textbf{{{T.ppl_cell(qd)}}}",
    ]
    header = r"Compensation & Mask & WikiText-2 test (val)"
    return "mask_selection", _render("llc", header, [rows])


# --------------------------------------------------------------------------- #
# Table 7 -- (alpha, gamma) grid (7B W4A4, s50 and s70)
# --------------------------------------------------------------------------- #
def alpha_gamma_grid(runs) -> tuple[str, str]:
    axis = [0.0, 0.25, 0.5]

    def grid(pattern):
        tags = runs.get(("llama2-7b", "W4A4", pattern, CALIB))
        if not tags:
            raise SystemExit(f"alpha_gamma_grid: no 7B W4A4 {pattern} data")
        cells = {}
        for tag, record in tags.items():
            if "@" in tag:
                continue
            mix = T.mix_of(tag)
            if mix and mix[0] in axis and mix[1] in axis:
                cells[mix] = T._val(record)
        return cells

    g50, g70 = grid("s50"), grid("s70")
    best50, best70 = min(g50.values()), min(g70.values())

    def fmt(cells, a, g, best):
        v = cells.get((a, g))
        if v is None:
            return "--"
        return f"\\textbf{{{v:.2f}}}" if v == best else f"{v:.2f}"

    rows = []
    for a in axis:
        left = " & ".join(fmt(g50, a, g, best50) for g in axis)
        right = " & ".join(fmt(g70, a, g, best70) for g in axis)
        rows.append(f"$\\alpha{{=}}{a:g}$ & {left} & {right}")

    header = (
        r" & \multicolumn{3}{c}{50\% sparsity} & \multicolumn{3}{c}{70\% sparsity} \\"
        + "\n"
        + r"$\alpha$ & $\gamma{=}0$ & $\gamma{=}0.25$ & $\gamma{=}0.5$ "
        + r"& $\gamma{=}0$ & $\gamma{=}0.25$ & $\gamma{=}0.5$"
    )
    body = _render("l" + "c" * 6, header, [rows])
    return "alpha_gamma_grid", body


# --------------------------------------------------------------------------- #
# target roles -- what each target contributes alone and together (Sec. 6)
# --------------------------------------------------------------------------- #
ROLE_SPEC = [
    ("llama2-7b", "W4A4", "s50"), ("llama2-7b", "W4A4", "4to8p-obs"),
    ("llama2-7b", "W2A16", "s50"), ("llama2-7b", "W4A4", "s60"),
    ("llama2-7b", "W4A4", "s70"),
]
# Which grid points each column searches: the asymmetric target alone (gamma = 0),
# the clean target alone (alpha = 0), and both together.
ROLES = {
    "asym": lambda a, g: a > 0 and g == 0,
    "clean": lambda a, g: a == 0 and g > 0,
    "joint": lambda a, g: a > 0 and g > 0,
}


def role_bests(tags: dict[str, dict]) -> tuple[float, dict[str, tuple[float, tuple]]]:
    """OBR's validation PPL and, per role, the best validation PPL and its mixture."""
    points = {T.mix_of(t): T._val(r) for t, r in tags.items()
              if "@" not in t and t != T.AUTO_TAG}
    bests = {}
    for role, keep in ROLES.items():
        cells = [(v, mix) for mix, v in points.items() if keep(*mix)]
        if cells:
            bests[role] = min(cells)
    return points[(0.0, 0.0)], bests


def target_roles(runs) -> tuple[str, str]:
    """Best validation perplexity change against OBR with the asymmetric target
    only, the clean target only, and both, per setting (seed 42)."""
    blocks: list[list[str]] = []
    for model, bits, pattern in ROLE_SPEC:
        tags = runs.get((model, bits, pattern, CALIB))
        if not tags:
            print(f"  skip role row {model} {bits} {pattern}: no data")
            continue
        obr, bests = role_bests(tags)
        best = min(v for v, _ in bests.values())
        cells = []
        for role in ROLES:
            if role not in bests:
                cells.append("--")
                continue
            v, (a, g) = bests[role]
            delta = f"{100 * (v / obr - 1):+.1f}\\%"
            delta = f"$\\mathbf{{{delta}}}$" if v == best else f"${delta}$"
            mix = f"{a:g}" if role == "asym" else f"{g:g}" if role == "clean" else f"{a:g},{g:g}"
            cells.append(f"{delta} ({mix})")
        if not blocks or blocks[-1][0].split(" & ")[0] != MODEL_DISP[model]:
            blocks.append([])
        setting = SPARSITY_DISP.get(pattern) or _nm_label(pattern, "pairwise 4:8", "mixed 4:8")
        blocks[-1].append(" & ".join([
            MODEL_DISP[model], f"{T.BITS_LABEL[bits]} {setting}", f"{obr:.2f}", *cells,
        ]))
    header = (r"Model & Setting & OBR (val) & asymmetric only ($\alpha$) "
              r"& clean only ($\gamma$) & both ($\alpha,\gamma$)")
    return "target_roles", _render("llcccc", header, blocks)


