import tablekit as T

MODEL_DISP = {"llama2-7b": "LLaMA-2-7B", "llama3.1-8b": "LLaMA-3.1-8B", "llama2-13b": "LLaMA-2-13B"}
SPARSITY_DISP = {"s50": r"50\%", "s60": r"60\%", "s70": r"70\%"}
CALIB = "128x1024"


def _sel_label(obr: dict, selected: dict) -> str:
    if selected is obr:
        return "OBR"
    alpha, gamma = T.mix_of(selected["calibration"])
    return f"$({alpha:g}, {gamma:g})$"


def _mean_mix_cell(record: dict) -> str:
    """Mean derived ``(alpha, gamma)`` over the layers of a QDrift run."""
    mix = T.mean_mix(record)
    return "--" if mix is None else f"$({mix[0]:.2f}, {mix[1]:.2f})$"


def _setting_label(bits: str, pattern: str) -> str:
    if pattern.startswith("4to8"):
        return T.BITS_LABEL[bits] + _nm_label(pattern, " pairwise 4:8", " mixed 4:8")
    return f"{T.BITS_LABEL[bits]} {SPARSITY_DISP[pattern]}"


