GRID_SPEC = [(m, b, p) for m, b, p in MAIN_SPEC if m == "llama2-7b"]


def grid_vs_derived(runs) -> tuple[str, str]:
    """LLaMA-2-7B: OBR, the pure asymmetric target, the best fixed (alpha, gamma)
    of the grid (chosen on validation PPL) and QDrift's derived mixture, with
    the number of compressions the grid needs."""
    rows = []
    for model, bits, pattern in GRID_SPEC:
        tags = runs.get((model, bits, pattern, CALIB))
        if not tags:
            continue
        obr, pure, sel = T.select(tags)
        qd = T.qdrift_of(tags)
        if obr is None or qd is None:
            print(f"  skip grid row {bits} {pattern}: no OBR/QDrift pair")
            continue
        best = min((sel, qd), key=lambda r: r["ppl"]["wikitext2"])

        def cell(record):
            text = r"%s$_{(%+.1f\%%)}$" % (T.ppl_cell(record), T.delta_vs_obr(record, obr))
            return r"\textbf{%s}" % text if record is best else text

        rows.append(" & ".join([
            _setting_label(bits, pattern), T.ppl_cell(obr), T.ppl_cell(pure),
            cell(sel), _sel_label(obr, sel), str(T.grid_size(tags)), cell(qd),
        ]))
    header = (r"Setting & OBR & $(1,0)$ & best grid point & $(\alpha,\gamma)$ "
              r"& grid runs & QDrift (derived)")
    return "grid_vs_derived", _render("lcccccc", header, [rows])


