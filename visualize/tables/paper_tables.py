"""Generate every paper table as a booktabs ``.tex`` fragment and a compiled PDF.

Each table is written to ``tables/tex/<name>.tex`` (``\\input`` it in the paper),
``tables/pdf/<name>.pdf`` (standalone) and ``tables/png/<name>.png`` (preview).  Data
tables are pulled live from ``results/v2`` and ``results/fp16``; the GEMM
microbenchmark is the one measured constant (``GEMM_US``).  The numbers the text
cites are generated by ``paper_numbers.py`` from the same selection.

    python visualize/tables/paper_tables.py            # build all
    python visualize/tables/paper_tables.py --only main_results seed_robustness
    python visualize/tables/paper_tables.py --list

QDrift is the run with the per-layer mixture derived from the calibration
statistics (``--mix-rule auto``, tag ``qdrift-auto``).  The fixed-weight (alpha,
gamma) grid is run on LLaMA-2-7B only, where ``grid_vs_derived``, ``alpha_sweep``,
``alpha_gamma_grid`` and ``target_roles`` compare it with QDrift.

Name -> paper table:
    main_results · grid_vs_derived · seed_robustness · alpha_sweep · mask_selection
    · gemm_efficiency · deploy_efficiency · alpha_gamma_grid · compression_time · asymmetric_overfit
    · localization · zeroshot · zeroshot_full · target_roles
"""

from __future__ import annotations

