# Dense vs pairwise-4:8 sparse INT4 GEMM, LLaMA-2-7B linear shapes, SM 8.9, measured once
# with benchmark/kernels/checks/w4a4_check.py::bench_shape (not saved as a record).
# Per phase: (dense us, sparse us, speedup); the speedup is from the unrounded timings.
GEMM_US = [
    {"layer": "q/o-proj", "shape": r"$4096\times4096$",
     "prefill": (73.5, 60.8, 1.21), "decode": (31.5, 16.8, 1.87)},
    {"layer": "gate/up-proj", "shape": r"$11008\times4096$",
     "prefill": (226.9, 169.1, 1.34), "decode": (31.4, 12.0, 2.61)},
    {"layer": "down-proj", "shape": r"$4096\times11008$",
     "prefill": (163.1, 143.6, 1.14), "decode": (75.9, 24.8, 3.05)},
]


def gemm_efficiency(_runs) -> tuple[str, str]:
    """Table 6 -- dense vs pairwise-4:8 sparse INT4 GEMM (``GEMM_US``)."""
    best = max(row["decode"][2] for row in GEMM_US)
    rows = []
    for row in GEMM_US:
        cells = [row["layer"], row["shape"]]
        for phase in ("prefill", "decode"):
            dense, sparse, speedup = row[phase]
            cell = f"{speedup:.2f}$\\times$"
            if phase == "decode" and speedup == best:
                cell = f"\\textbf{{{cell}}}"
            cells += [f"{dense:.1f}", f"{sparse:.1f}", cell]
        rows.append(" & ".join(cells))
    header = (
        r" & & \multicolumn{2}{c}{Prefill ($R{=}2048$)} & & \multicolumn{2}{c}{Decode ($R{=}32$)} & \\"
        + "\n"
        + r"\cmidrule(lr){3-4}\cmidrule(lr){6-7}"
        + "\n"
        + r"Layer & Shape ($c_{out}{\times}c_{in}$) & Dense & Sparse & Speedup & Dense & Sparse & Speedup"
    )
    body = _render("llcccccc", header, [rows])
    return "gemm_efficiency", body


OVERFIT_SPEC = [
    (model, bits, pattern)
    for model in ("llama2-7b", "llama3.1-8b", "llama2-13b")
    for bits, pattern in (("W4A4", "s50"), ("W4A4", "s60"), ("W4A4", "s70"),
                          ("W4A16", "s70"), ("W2A16", "s50"))
]


def asymmetric_overfit(runs) -> tuple[str, str]:
    """Table 1 -- OBR vs the pure asymmetric target (1, 0) on the main calibration."""
    blocks: list[list[str]] = []
    for model, bits, pattern in OVERFIT_SPEC:
        tags = runs.get((model, bits, pattern, CALIB))
        if not tags:
            print(f"  skip overfit row {model} {bits} {pattern}: no data")
            continue
        obr, pure, _ = T.select(tags)
        if obr is None or pure is None:
            continue
        if not blocks or blocks[-1][0].split(" & ")[0] != MODEL_DISP[model]:
            blocks.append([])
        blocks[-1].append(" & ".join([
            MODEL_DISP[model], T.BITS_LABEL[bits], SPARSITY_DISP[pattern],
            T.ppl_cell(obr), T.ppl_cell(pure), f"${T.delta_vs_obr(pure, obr):+.1f}\\%$",
        ]))
    header = r"Model & Setting & Sparsity & OBR & Asymmetric $(1,0)$ & vs OBR"
    return "asymmetric_overfit", _render("lllccc", header, blocks)


LOCALIZATION_BASE = "llama2-7b_obr_w4a4_s70_c128x1024"
LOCALIZATION_ROWS = [
    ("none (OBR)", "seq"), ("blocks 0--3", "qdrift-L0-3"), ("blocks 0--7", "qdrift-L0-7"),
    ("blocks 0--11", "qdrift-L0-11"), ("blocks 0--15", "qdrift-L0-15"),
    ("blocks 8--31", "qdrift-L8-31"), ("attention only", "qdrift-Mattn"),
    ("MLP gate/up only", "qdrift-Mmlp_in"), ("MLP down\\_proj only", "qdrift-Mmlp_out"),
    ("all blocks", "qdrift"),
]


def localization(_runs) -> tuple[str, str]:
    """Table 2 -- the pure asymmetric target (1, 0) on a subset of layers only,
    OBR elsewhere (7B W4A4KV4 s70, 128x1024).  The localized runs are read by
    name; they are off the selection grid, so ``load_runs`` drops them."""
    records = {}
    for label, tag in LOCALIZATION_ROWS:
        path = T.RESULTS_V2 / f"{LOCALIZATION_BASE}_{tag}_seed42.json"
        record = json.loads(path.read_text(encoding="utf-8")) if path.exists() else None
        if record is None or "wikitext2" not in (record.get("ppl") or {}):
            print(f"  skip localization row {label}: no result")
            continue
        records[label] = record
    obr = records.get("none (OBR)")
    if obr is None or len(records) < 3:
        raise SystemExit("localization: the localized runs have not landed yet")
    rows = []
    for label, _ in LOCALIZATION_ROWS:
        if label in records:
            delta = T.delta_vs_obr(records[label], obr)
            rows.append(" & ".join([label, T.ppl_cell(records[label]),
                                    "--" if records[label] is obr else f"${delta:+.1f}\\%$"]))
    header = r"Layers with asymmetric target & WikiText-2 test (val) & vs OBR"
    return "localization", _render("lcc", header, [rows])


# --------------------------------------------------------------------------- #
# Rendering + driver
# --------------------------------------------------------------------------- #
def _render(colspec: str, header: str, blocks: list[list[str]]) -> str:
    """A booktabs tabular whose row blocks are separated by ``\\midrule``.  A model
    name in the first column is printed only where it changes within a block."""
    lines = [r"\begin{tabular}{%s}" % colspec, r"\toprule", header + r" \\", r"\midrule"]
    names = set(MODEL_DISP.values())
    for i, block in enumerate(blocks):
        if i:
            lines.append(r"\midrule")
        shown = None
        for row in block:
            first, sep, rest = row.partition(" & ")
            if first in names:
                if first == shown:
                    row = sep + rest
                shown = first
            lines.append(row + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines)


# --------------------------------------------------------------------------- #
# Table 3c / F1 -- zero-shot accuracy per task, OBR vs the selected mixture
# --------------------------------------------------------------------------- #
ZEROSHOT_TASKS = (("piqa", "PIQA"), ("hellaswag", "HellaS."), ("arc_easy", "ARC-e"),
                  ("arc_challenge", "ARC-c"), ("winogrande", "Wino."),
                  ("lambada_openai", "LAMB."), ("avg", "Avg."))
# Main text: the deployable layout and the two ends of the bit-width range.
ZEROSHOT_MAIN = {("W4A4", "s50"), ("W4A4", "4to8p-obs"), ("W4A4", "4to8p40-obs"),
                 ("W2A16", "s50")}


FP16_RESULTS = T.ROOT / "results" / "fp16"


def _fp16_zeroshot_row(model: str) -> list[str]:
    """The uncompressed fp16 reference of a model (never bolded), if evaluated."""
    path = FP16_RESULTS / f"{model}__zeroshot.json"
    if not path.exists():
        print(f"  no fp16 zeroshot reference for {model}")
        return []
    scores = json.loads(path.read_text(encoding="utf-8"))["zeroshot"]
    cells = [f"{float(scores[key]):.1f}" for key, _ in ZEROSHOT_TASKS]
    return [" & ".join([MODEL_DISP[model], "FP16 reference", "dense", *cells])]


def _zeroshot_rows(runs, keep) -> list[list[str]]:
    """Two rows (OBR, QDrift) per setting, one block per model; in every column
    the higher accuracy of the pair is bold (zero-shot is not uniformly in
    QDrift's favor).  Settings without a ``zeroshot`` field are skipped."""
    blocks: dict[str, list[str]] = {}
    for model, bits, pattern in MAIN_SPEC:
        if not keep(bits, pattern):
            continue
        tags = runs.get((model, bits, pattern, CALIB))
        if not tags:
            continue
        obr, _, sel = T.select(tags)
        if obr is None or sel is None:
            continue
        oz, sz = obr.get("zeroshot"), sel.get("zeroshot")
        if not oz or not sz:
            print(f"  skip zeroshot row {model} {bits} {pattern}: no zeroshot")
            continue
        pairwise = pattern.startswith("4to8")
        setting = T.BITS_LABEL[bits] + (_nm_label(pattern, " 4:8p", " 4:8m") if pairwise
                                         else f" {SPARSITY_DISP[pattern]}")
        ocells, scells = [], []
        for key, _ in ZEROSHOT_TASKS:
            oa, sa = round(float(oz[key]), 1), round(float(sz[key]), 1)
            ocells.append(f"$\\mathbf{{{oa:.1f}}}$" if oa > sa else f"{oa:.1f}")
            scells.append(f"$\\mathbf{{{sa:.1f}}}$" if sa > oa else f"{sa:.1f}")
        if model not in blocks:
            blocks[model] = _fp16_zeroshot_row(model)
        rows = blocks[model]
        rows.append(" & ".join([MODEL_DISP[model], setting, "OBR", *ocells]))
        rows.append(" & ".join(["", "", f"QDrift {_sel_label(obr, sel)}", *scells]))
    if not blocks:
        raise SystemExit("zeroshot: no results carry a zeroshot field yet")
    return list(blocks.values())


def _zeroshot_table(runs, keep) -> str:
    header = "Model & Setting & Method & " + " & ".join(label for _, label in ZEROSHOT_TASKS)
    return _render("lll" + "c" * len(ZEROSHOT_TASKS), header, _zeroshot_rows(runs, keep))


def zeroshot(runs) -> tuple[str, str]:
    """Main-text zero-shot table: W4A4 50%, pairwise 4:8 and W2A16 per model."""
    return "zeroshot", _zeroshot_table(runs, lambda b, p: (b, p) in ZEROSHOT_MAIN)


def zeroshot_full(runs) -> tuple[str, str]:
    """Appendix zero-shot table: every row of Table 3."""
    return "zeroshot_full", _zeroshot_table(runs, lambda b, p: True)


BUILDERS = {
    "main_results": main_results,
    "seed_robustness": seed_robustness,
    "alpha_sweep": alpha_sweep,
    "mask_selection": mask_selection,
    "gemm_efficiency": gemm_efficiency,
    "alpha_gamma_grid": alpha_gamma_grid,
    "compression_time": compression_time,
    "asymmetric_overfit": asymmetric_overfit,
    "localization": localization,
    "zeroshot": zeroshot,
    "zeroshot_full": zeroshot_full,
}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--only", nargs="*", choices=list(BUILDERS), help="build a subset")
    parser.add_argument("--folder", default=str(T.RESULTS_V2), help="v2 results folder")
    parser.add_argument("--list", action="store_true", help="list table names and exit")
    args = parser.parse_args()
    if args.list:
        for name in BUILDERS:
            print(name)
        return
    runs = T.load_runs(args.folder)
    for name in args.only or list(BUILDERS):
        try:
            table_name, body = BUILDERS[name](runs)
        except SystemExit as err:
            print(f"skip {name}: {err}")
            continue
        T.save_table(table_name, body)


if __name__ == "__main__":
    main()
